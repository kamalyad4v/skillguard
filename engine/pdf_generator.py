                table_rows = re.findall(r'\|\s*(High|Medium|Low|Info)\s*\|\s*(\d+)\s*\|\s*([^\|\n]+)', raw_markdown, re.IGNORECASE)
                for sev, cnt_str, desc in table_rows:
                    cnt = int(cnt_str)
                    items = [it.strip() for it in desc.split(',') if it.strip()]
                    for item in items:
                        all_findings.append({
                            "severity": sev.upper(),
                            "rule": item,
                            "description": f"Security audit identified: {item}",
                        })

