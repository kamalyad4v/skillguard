class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to dynamically compute and print 'Page X of Y' page numbers
    along with a confidential audit watermark header and footer.
    """

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica-Bold", 7.5)
        self.setFillColor(colors.HexColor("#64748b"))

        # Top Running Header (Pages > 1)
        if self._pageNumber > 1:
            self.drawString(40, 762, "SKILLGUARD // AUTONOMOUS RED TEAM AUDIT DOSSIER")
            self.drawRightString(letter[0] - 40, 762, "CONFIDENTIAL / STRICTLY RESTRICTED")
            self.setStrokeColor(colors.HexColor("#1e293b"))
            self.setLineWidth(0.75)
            self.line(40, 755, letter[0] - 40, 755)

        # Bottom Running Footer
        self.setStrokeColor(colors.HexColor("#1e293b"))
        self.setLineWidth(0.75)
        self.line(40, 42, letter[0] - 40, 42)

        self.setFont("Helvetica", 7.5)
        self.setFillColor(colors.HexColor("#94a3b8"))
        self.drawString(40, 30, "Generated by SkillGuard Autonomous Security Engine (NIST SP 800-115 / OWASP WSTG v4.2)")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(letter[0] - 40, 30, page_str)
        self.restoreState()


