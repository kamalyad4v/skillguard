    def _format_attack_verdict(self, findings: Optional[List[Dict[str, Any]]]) -> str:
        if findings is None:
            return "<font color='#64748b'>SKIPPED (No vector)</font>"
        non_info = [f for f in findings if f.get("severity") in ["HIGH", "MEDIUM", "LOW"]]
        if non_info:
            return f"<font color='#ff3366'><b>VULNERABLE ({len(non_info)} issues)</b></font>"
        return "<font color='#00ff9d'><b>CLEAN (Defended)</b></font>"

    def _enrich_finding_metadata(self, f: Dict[str, Any]) -> Dict[str, Any]:
        """Provides CVSS v3.1, CWE, OWASP, and code remediation snippets."""
        rule = (f.get("rule") or "").upper()
        sev = (f.get("severity") or "INFO").upper()

        if "SQLI" in rule:
            cwe = "CWE-89: SQL Injection"
            cvss_score = 9.8 if sev == "HIGH" else 8.5
            cvss_vector = "CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:U/C:H/I:H/A:H"
            owasp = "A03:2021 - Injection"
            impact = "Full database compromise, authentication bypass, data exfiltration, remote command execution."
            reproduction = "1. Pass SQL payload marker: ' OR 1=1-- into parameters.\n2. Observe reflected SQL syntax error or bypass."
            remediation = "Enforce parameterized prepared statements across all queries. Never concatenate untrusted strings."
        elif "XSS" in rule:
            cwe = "CWE-79: Cross-Site Scripting"
            cvss_score = 7.2 if sev == "HIGH" else 6.1
            cvss_vector = "CVSS:3.1/AV:N/AC:L/PR:N/UI:R/S:C/C:L/I:L/A:N"
            owasp = "A03:2021 - Injection"
            impact = "Session hijacking, credential theft via cookie extraction, unauthorized actions on behalf of victims."
            reproduction = "1. Inject <script>alert(document.domain)</script> into input.\n2. Verify unencoded DOM reflection."
            remediation = "Apply contextual output encoding (HTML, JS, Attribute) and enforce a strict Content-Security-Policy (CSP)."
        elif "CSRF" in rule:
            cwe = "CWE-352: Cross-Site Request Forgery"
            cvss_score = 6.5
            cvss_vector = "CVSS:3.1/AV:N/AC:L/PR:N/UI:R/S:U/C:N/I:H/A:N"
            owasp = "A01:2021 - Broken Access Control"
            impact = "Unauthorized state changes executed on behalf of authenticated users."
            reproduction = "1. Verify state-changing form submission without anti-CSRF token."
            remediation = "Issue unique anti-CSRF tokens for all state changes and set SameSite=Lax on cookies."
        elif "HEADER" in rule:
            cwe = "CWE-693: Protection Mechanism Failure"
            cvss_score = 4.3
            cvss_vector = "CVSS:3.1/AV:N/AC:L/PR:N/UI:R/S:U/C:L/I:N/A:N"
            owasp = "A05:2021 - Security Misconfiguration"
            impact = "Clickjacking, MIME sniffing, and protocol downgrade exposure."
            reproduction = "1. Inspect response headers using curl -I.\n2. Verify missing CSP, HSTS, X-Frame-Options."
            remediation = "Configure defensive headers in Nginx/Apache: Content-Security-Policy, HSTS, X-Frame-Options: DENY."
        elif "SSL" in rule or "TLS" in rule:
            cwe = "CWE-295: Improper Certificate Validation"
            cvss_score = 5.9
            cvss_vector = "CVSS:3.1/AV:N/AC:H/PR:N/UI:N/S:U/C:H/I:N/A:N"
            owasp = "A02:2021 - Cryptographic Failures"
            impact = "Susceptibility to Man-in-the-Middle (MitM) and traffic eavesdropping."
            reproduction = "1. Query SSL endpoint with testssl or openssl s_client."
            remediation = "Enforce TLS 1.2+ minimum, disable weak ciphers (RC4, 3DES), and install valid CA certificates."
        else:
            cwe = "CWE-200: Exposure of Sensitive Information"
            cvss_score = 3.5
            cvss_vector = "CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:U/C:L/I:N/A:N"
            owasp = "A05:2021 - Security Misconfiguration"
            impact = "Leakage of server metadata and structural details assisting attackers."
            reproduction = "1. Inspect verbose response banners and debug error outputs."
            remediation = "Disable server version banners and adhere to CIS hardening benchmarks."

        return {
            "cwe": cwe,
            "cvss_score": cvss_score,
            "cvss_vector": cvss_vector,
            "owasp": owasp,
            "impact": impact,
            "reproduction": reproduction,
            "remediation": remediation,
        }
