            score_match = re.search(r'>\s*(\d{1,3})\s*<span[^>]*>/100</span>', raw_markdown) or re.search(r'(\d{1,3})\s*/\s*100', raw_markdown)
            if score_match:
                try:
                    risk_score = int(score_match.group(1))
                except Exception:
                    pass
            grade_match = re.search(r'GRADE\s+([A-F])', raw_markdown, re.IGNORECASE)
            if grade_match:
                risk_grade = grade_match.group(1).upper()

            target_match = re.search(r'Target\s*(?:Host|System|URL)?[:\*`\s]+(https?://[^\s`\|]+)', raw_markdown, re.IGNORECASE)
            if target_match and (target == "https://target" or not target):
                target = target_match.group(1).strip()

            if "server_info" not in recon_results:
                recon_results["server_info"] = {}
            ip_m = re.search(r'\|\s*\*\*IP(?:\s*Address)?:\*\*\s*\|\s*([^\|\n]+)', raw_markdown, re.IGNORECASE)
            if ip_m:
                recon_results["server_info"]["ip_address"] = ip_m.group(1).strip()
            reg_m = re.search(r'\|\s*\*\*Registrar:\*\*\s*\|\s*([^\|\n]+)', raw_markdown, re.IGNORECASE)
            if reg_m:
                recon_results["server_info"]["registrar"] = reg_m.group(1).strip()
            srv_m = re.search(r'\|\s*\*\*Server(?:\s*Headers)?:\*\*\s*\|\s*([^\|\n]+)', raw_markdown, re.IGNORECASE)
            if srv_m:
                recon_results["server_info"]["server_header"] = srv_m.group(1).strip()

            finding_blocks = re.findall(r'###\s*Finding\s*[\d\.]+:\s*\[(HIGH|MEDIUM|LOW|INFO)\]\s*([^\n]+)([\s\S]*?)(?=###\s*Finding|\n##|\Z)', raw_markdown, re.IGNORECASE)
            for sev, rule, body in finding_blocks:
                desc_match = re.search(r'\-\s*\*\*Vulnerability Description:\*\*\s*([^\n]+)', body, re.IGNORECASE)
                desc = desc_match.group(1).strip() if desc_match else rule.strip()
                all_findings.append({
                    "severity": sev.upper(),
                    "rule": rule.strip(),
                    "description": desc,
                })

