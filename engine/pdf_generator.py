    def _sanitize(self, text: Any) -> str:
        """Escape XML entities for reportlab Paragraph."""
        if text is None:
            return ""
        s = str(text)
        s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        return s

